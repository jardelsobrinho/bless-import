SET SQL DIALECT 3;

CREATE TABLE EXECUCAO (
  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ID_PERFIL       INTEGER NOT NULL,
  VERSAO_PERFIL   INTEGER NOT NULL,          /* versão do perfil usada nesta execução */
  ARQUIVO         VARCHAR(500) NOT NULL,
  ABA             VARCHAR(100),
  CONEXAO         VARCHAR(400),              /* nome e banco de destino, para o histórico */
  TABELA_DESTINO  VARCHAR(63) NOT NULL,
  ESTRATEGIA      VARCHAR(30) NOT NULL,
  ACAO_ERRO       VARCHAR(20) NOT NULL,
  INICIO          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  FIM             TIMESTAMP,
  STATUS          VARCHAR(30) NOT NULL,      /* EM_ANDAMENTO, CONCLUIDA, CONCLUIDA_COM_ERROS, INTERROMPIDA, CANCELADA, DESFEITA, FALHOU */
  LINHAS_LIDAS    INTEGER DEFAULT 0 NOT NULL,
  INSERIDAS       INTEGER DEFAULT 0 NOT NULL,
  ATUALIZADAS     INTEGER DEFAULT 0 NOT NULL,
  IGNORADAS       INTEGER DEFAULT 0 NOT NULL,
  VALIDADAS       INTEGER DEFAULT 0 NOT NULL,  /* estratégia "só validar": linhas sem erro */
  COM_ERRO        INTEGER DEFAULT 0 NOT NULL,
  VAZIAS          INTEGER DEFAULT 0 NOT NULL,
  ULTIMA_LINHA    INTEGER DEFAULT 0 NOT NULL,  /* última linha da planilha com gravação confirmada (commit) */
  MENSAGEM        VARCHAR(1000),
  CONSTRAINT PK_EXECUCAO PRIMARY KEY (ID),
  CONSTRAINT FK_EXECUCAO_PERFIL FOREIGN KEY (ID_PERFIL) REFERENCES PERFIL (ID) ON DELETE CASCADE
);
COMMIT;

CREATE INDEX IX_EXECUCAO_PERFIL ON EXECUCAO (ID_PERFIL, INICIO);
COMMIT;

CREATE TABLE EXECUCAO_ERRO (
  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ID_EXECUCAO     INTEGER NOT NULL,
  LINHA           INTEGER NOT NULL,          /* linha da planilha */
  CAMPO           VARCHAR(63),               /* vazio = erro da linha inteira (ex.: gravação) */
  TIPO_ERRO       VARCHAR(20) NOT NULL,      /* VALIDACAO, TRANSFORMACAO, REFERENCIA, GRAVACAO */
  VALOR_RECEBIDO  VARCHAR(1000),
  MENSAGEM        VARCHAR(2000) NOT NULL,
  CONSTRAINT PK_EXECUCAO_ERRO PRIMARY KEY (ID),
  CONSTRAINT FK_EXECUCAO_ERRO_EXECUCAO FOREIGN KEY (ID_EXECUCAO) REFERENCES EXECUCAO (ID) ON DELETE CASCADE
);
COMMIT;

/* Textos do banco de configuração em UTF8 */
ALTER DATABASE SET DEFAULT CHARACTER SET UTF8;
COMMIT;

CREATE TABLE CONEXAO (
  ID        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOME      VARCHAR(60) NOT NULL,
  ERP       VARCHAR(20) NOT NULL,
  SERVIDOR  VARCHAR(100) NOT NULL,
  PORTA     INTEGER DEFAULT 3050 NOT NULL,
  BANCO     VARCHAR(255) NOT NULL,
  USUARIO   VARCHAR(60) NOT NULL,
  SENHA     VARCHAR(1000),          /* criptografada (DPAPI do Windows, base64) */
  CHARSET   VARCHAR(20) DEFAULT 'WIN1252' NOT NULL,
  DIALETO   SMALLINT DEFAULT 1 NOT NULL,
  CONSTRAINT PK_CONEXAO PRIMARY KEY (ID),
  CONSTRAINT UK_CONEXAO_NOME UNIQUE (NOME),
  CONSTRAINT CK_CONEXAO_DIALETO CHECK (DIALETO IN (1, 3))
);
COMMIT;

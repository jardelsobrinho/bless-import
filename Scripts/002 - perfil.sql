SET SQL DIALECT 3;

CREATE TABLE PERFIL (
  ID               INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOME             VARCHAR(100) NOT NULL,
  DESCRICAO        VARCHAR(500),
  ID_CONEXAO       INTEGER NOT NULL,
  TABELA_DESTINO   VARCHAR(63) NOT NULL,
  ARQUIVO_EXEMPLO  VARCHAR(500),               /* planilha usada para montar o mapeamento */
  ABA              VARCHAR(100),
  LINHA_CABECALHO  INTEGER DEFAULT 1 NOT NULL,  /* 0 = sem cabeçalho */
  LINHA_INICIAL    INTEGER DEFAULT 2 NOT NULL,
  ESTRATEGIA       VARCHAR(30) DEFAULT 'INSERIR' NOT NULL,     /* usado na gravação (T08) */
  CAMPOS_CHAVE     VARCHAR(500),                               /* campos que identificam o registro (T08) */
  ACAO_ERRO        VARCHAR(20) DEFAULT 'CONTINUAR' NOT NULL,   /* usado na gravação (T08) */
  VERSAO           INTEGER DEFAULT 1 NOT NULL,                 /* +1 a cada gravação */
  DATA_ALTERACAO   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT PK_PERFIL PRIMARY KEY (ID),
  CONSTRAINT UK_PERFIL_NOME UNIQUE (NOME),
  CONSTRAINT FK_PERFIL_CONEXAO FOREIGN KEY (ID_CONEXAO) REFERENCES CONEXAO (ID),
  CONSTRAINT CK_PERFIL_LINHAS CHECK (LINHA_CABECALHO >= 0 AND LINHA_INICIAL > LINHA_CABECALHO)
);
COMMIT;

/* Um registro por campo de destino mapeado (campos "não importar" não são gravados) */
CREATE TABLE PERFIL_CAMPO (
  ID                       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ID_PERFIL                INTEGER NOT NULL,
  ORDEM                    INTEGER NOT NULL,
  CAMPO_DESTINO            VARCHAR(63) NOT NULL,
  ORIGEM                   VARCHAR(20) NOT NULL,   /* COLUNA, FIXO, PADRAO, CONSULTA, GERADO, EXPRESSAO */
  COLUNA                   VARCHAR(200),           /* nome da coluna na planilha (COLUNA, PADRAO, CONSULTA) */
  VALOR_FIXO               VARCHAR(1000),
  VALOR_PADRAO             VARCHAR(1000),
  PADRAO_SE_INEXISTENTE    CHAR(1) DEFAULT 'S' NOT NULL,
  PADRAO_SE_VAZIO          CHAR(1) DEFAULT 'S' NOT NULL,
  PADRAO_SE_INVALIDO       CHAR(1) DEFAULT 'N' NOT NULL,
  GENERATOR                VARCHAR(63),
  EXPRESSAO                VARCHAR(1000),          /* modelo, ex.: {Endereco}, {Numero} */
  CONSULTA_TABELA          VARCHAR(63),
  CONSULTA_CAMPO_PESQUISA  VARCHAR(63),
  CONSULTA_CAMPO_RETORNO   VARCHAR(63),
  CONSULTA_SE_NAO_ACHAR    VARCHAR(20) DEFAULT 'PENDENCIA' NOT NULL,
  TRANSFORMACOES           BLOB SUB_TYPE TEXT,     /* uma por linha: CODIGO|parâmetro */
  CONSTRAINT PK_PERFIL_CAMPO PRIMARY KEY (ID),
  CONSTRAINT UK_PERFIL_CAMPO UNIQUE (ID_PERFIL, CAMPO_DESTINO),
  CONSTRAINT FK_PERFIL_CAMPO_PERFIL FOREIGN KEY (ID_PERFIL) REFERENCES PERFIL (ID) ON DELETE CASCADE,
  CONSTRAINT CK_PERFIL_CAMPO_ORIGEM CHECK (ORIGEM IN ('COLUNA', 'FIXO', 'PADRAO', 'CONSULTA', 'GERADO', 'EXPRESSAO')),
  CONSTRAINT CK_PERFIL_CAMPO_FLAGS CHECK (PADRAO_SE_INEXISTENTE IN ('S', 'N') AND PADRAO_SE_VAZIO IN ('S', 'N')
    AND PADRAO_SE_INVALIDO IN ('S', 'N'))
);
COMMIT;
